local config = require("bridge.config")

describe("bridge.config.parse_ipv4", function()
	it("accepts a dotted-quad address and trims whitespace", function()
		assert.equal("192.0.2.10", config.parse_ipv4(" 192.0.2.10 "))
	end)

	it("rejects empty input", function()
		local ip, err = config.parse_ipv4("")
		assert.is_nil(ip)
		assert.equal("empty", err)
	end)

	it("rejects out-of-range octets", function()
		assert.is_nil(config.parse_ipv4("192.0.2.256"))
	end)

	it("rejects leading zeros", function()
		assert.is_nil(config.parse_ipv4("192.0.2.010"))
	end)

	it("rejects hostnames and partial addresses", function()
		assert.is_nil(config.parse_ipv4("hue-bridge.local"))
		assert.is_nil(config.parse_ipv4("192.0.2"))
	end)

	it("rejects non-strings", function()
		assert.is_nil(config.parse_ipv4(nil))
	end)
end)

describe("bridge.config.normalise_bridge_id", function()
	it("lower-cases a Bridge Pro style upper-case id", function()
		assert.equal("0017880000abcdef", config.normalise_bridge_id("0017880000ABCDEF"))
	end)

	it("rejects ids of the wrong length or with non-hex characters", function()
		assert.is_nil(config.normalise_bridge_id("0017880000abcde"))
		assert.is_nil(config.normalise_bridge_id("0017880000abcdeg"))
	end)
end)

describe("bridge.config bridge generations (docs/bridge-compat-design.md)", function()
	it("labels the models with their friendly names", function()
		assert.equal("Hue Bridge Pro (BSB003)", config.model_label("BSB003"))
		assert.equal("Hue Bridge v2, square (BSB002)", config.model_label("BSB002"))
		assert.equal("Hue Bridge v1, round (BSB001)", config.model_label("BSB001"))
		assert.equal("Hue bridge BSB004 (untested model)", config.model_label("BSB004"))
		assert.equal("XYZ (not a Hue bridge)", config.model_label("XYZ"))
		assert.equal("", config.model_label(nil))
	end)

	it("supports v2, Pro and newer Hue models, not v1 or other devices", function()
		assert.is_true(config.model_supported("BSB002"))
		assert.is_true(config.model_supported("BSB003"))
		assert.is_true(config.model_supported("BSB004"))
		assert.is_false(config.model_supported("BSB001"))
		assert.is_false(config.model_supported("XYZ"))
		assert.is_false(config.model_supported(nil))
	end)

	it("checks and labels the firmware", function()
		assert.equal("ok", config.firmware_check("1968096020"))
		assert.equal("old", config.firmware_check("1941132080"))
		assert.equal("unknown", config.firmware_check("x"))
		assert.equal("1968096020 (API 1.68.0)", config.firmware_label("1968096020", "1.68.0"))
		assert.equal("1941132080; older than 1948086000, update the bridge in the Hue app",
			config.firmware_label("1941132080", nil))
		assert.equal("", config.firmware_label(nil, "1.68.0"))
	end)
end)
